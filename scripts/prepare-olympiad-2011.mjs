import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
const project = path.resolve(import.meta.dirname, '..');
const source = path.resolve(project, '../../development/shared/nmr/olympiad-2011-q4/olympiad-2011-q4-compound-3.svg');
const expected = '07d75b648f1117fadaa701ecb875e68331f2dc4a8a451cea1f9591a257ea1d7d';
const bytes = fs.readFileSync(source);
const sha = b => crypto.createHash('sha256').update(b).digest('hex');
assert.equal(sha(bytes), expected, 'Approved spectrum changed; fresh user acceptance required');
const neutral = text => text.replace(/<metadata\b[\s\S]*?<\/metadata>/g, '').replace(/<title\b[^>]*>[\s\S]*?<\/title>/g, '').replace(/<desc\b[^>]*>[\s\S]*?<\/desc>/g, '');
const stripped = neutral(bytes.toString('utf8'));
const result = stripped.replace(/(<svg\b[^>]*>)/, '$1<title id="spectrum-title">Compound 3 proton NMR spectrum</title><desc id="spectrum-description">Proton NMR spectrum with signal labels, relative integrals, chemical shifts in ppm and expanded multiplets.</desc>');
assert.equal(neutral(result), stripped, 'Drawing content must be identical');
assert(!/methylpropan|butanol|OH broad|methine/i.test(result));
const target = path.join(project, 'src/activities/olympiad/isomers2011/assets/compound-3.svg');
fs.mkdirSync(path.dirname(target), {recursive:true});
fs.writeFileSync(target, result);
const evidence = path.join(project, '.artifacts/olympiad-2011-q4/implementation');
fs.mkdirSync(evidence, {recursive:true});
fs.writeFileSync(path.join(evidence, 'spectrum-provenance.json'), JSON.stringify({source: path.relative(project,source), sourceSha256: expected, runtimeSha256: sha(result), changes: 'Only metadata, title and description replaced; neutral-stripped SVG byte equality passes', generatedAt:new Date().toISOString()},null,2)+'\n');
console.log('Approved drawing content preserved; neutral runtime spectrum generated.');
