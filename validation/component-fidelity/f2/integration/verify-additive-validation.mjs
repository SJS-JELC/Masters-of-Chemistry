import fs from 'node:fs';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
const before=fs.readFileSync(new URL('./validation-before-numeric.ts',import.meta.url),'utf8');
const current=fs.readFileSync(new URL('../../../../src/persistence/validation.ts',import.meta.url),'utf8');
const numeric=text=>text.match(/    case 'numeric':[\s\S]*?      break;/)?.[0];
assert(numeric(before)&&numeric(current));
assert.equal(current.replace(numeric(current),numeric(before)),before,'Unrelated external validation source was changed during numeric integration');
const hash=value=>crypto.createHash('sha256').update(value).digest('hex');
fs.writeFileSync(new URL('./validation-additive-preservation.json',import.meta.url),JSON.stringify({status:'PASS',beforeSha256:hash(before),afterSha256:hash(current),outsideNumericSha256:hash(before.replace(numeric(before),'')),scope:'Only numeric response case changed; all concurrent Isomer imports/validation preserved byte-for-byte',externalContentAccepted:false},null,2)+'\n');
console.log('PASS: unrelated validation bytes preserved');
