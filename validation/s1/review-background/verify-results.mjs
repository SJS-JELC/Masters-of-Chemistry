import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {dirname,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
const here=dirname(fileURLToPath(import.meta.url));
const result=JSON.parse(readFileSync(resolve(here,'chrome-results.json'),'utf8'));
assert.equal(result.status,'PASS');
assert.equal(result.playwright,'1.62.1');
assert.equal(result.connection.noDefaults,true);
assert.equal(result.sourceUnchanged,true);
assert.deepEqual(result.errors,[]);
assert.deepEqual(result.firstAssessment.timing,result.firstAssessment.evidenceTiming);
assert.ok(result.firstAssessment.timing.activeMs>0);
const byLabel=Object.fromEntries(result.observations.map(value=>[value.label,value]));
assert.equal(byLabel['actual other tab foreground'].hidden,true);
assert.equal(byLabel['actual other tab foreground'].focused,false);
assert.equal(byLabel['actual other tab foreground'].timing.activeMs,byLabel['background after 3200ms'].timing.activeMs);
assert.equal(byLabel['background after 3200ms'].timing.activeMs,byLabel['return focus without interaction'].timing.activeMs);
assert.ok(byLabel['trusted input resumes'].timing.activeMs>byLabel['return focus without interaction'].timing.activeMs);
assert.equal(byLabel['actual browser window minimized'].window.bounds.windowState,'minimized');
assert.equal(byLabel['actual browser window minimized'].hidden,true);
assert.equal(byLabel['actual browser window minimized'].focused,false);
assert.equal(byLabel['actual browser window minimized'].timing.activeMs,byLabel['minimized after 2500ms'].timing.activeMs);
assert.equal(byLabel['minimized after 2500ms'].timing.activeMs,byLabel['window restored without interaction'].timing.activeMs);
assert.ok(result.nativeVisibilityEvents.some(value=>value.trusted&&value.name==='visibilitychange'&&value.hidden));
const evidence={status:'PASS',checkedAt:new Date().toISOString(),firstTimingMs:result.firstAssessment.timing.activeMs,sourceQuiescence:result.sourceUnchanged,scriptSha256:createHash('sha256').update(readFileSync(resolve(here,'background-check.mjs'))).digest('hex'),resultSha256:createHash('sha256').update(readFileSync(resolve(here,'chrome-results.json'))).digest('hex'),screenshotSha256:createHash('sha256').update(readFileSync(resolve(here,'chrome-background-restored-assessment.png'))).digest('hex')};
writeFileSync(resolve(here,'verification.json'),JSON.stringify(evidence,null,2)+'\n');
console.log(JSON.stringify(evidence));
